// Semester dates in YYYY-MM-DD format.
const SEMESTER_START = '2026-09-14';
const SEMESTER_END = '2026-12-14';

function setupMenu() {
    const button = document.querySelector('.menu-toggle');
    const menu = document.querySelector('.main-nav');
    button.onclick = function () {
        menu.classList.toggle('is-open');
        button.setAttribute('aria-expanded', menu.classList.contains('is-open'));
    };
}

function setupSchedule() {
    if (!document.querySelector('.schedule-table')) return;
    const lessons = document.querySelectorAll('.class-cell');
    const buttons = document.querySelectorAll('.filter-button');
    const status = document.querySelector('#lesson-status');
    const days = ['pondelok', 'utorok', 'stredu', 'štvrtok', 'piatok', 'sobotu', 'nedeľu'];

    for (const button of buttons) {
        button.onclick = function () {
            let count = 0;
            for (const lesson of lessons) {
                const show = button.dataset.filter === 'all' || lesson.classList.contains(button.dataset.filter);
                lesson.classList.toggle('filtered-out', !show);
                if (show) count++;
            }
            for (const other of buttons) {
                other.classList.toggle('active', other === button);
                other.setAttribute('aria-pressed', other === button);
            }
            document.querySelector('#filter-status').textContent = '';
            if (count === 0) document.querySelector('#filter-status').textContent = 'Pre tento filter nemám žiadne hodiny.';
        };
    }

    function updateLesson() {
        const now = new Date();
        const weekDay = (now.getDay() + 6) % 7;
        const time = weekDay * 1440 + now.getHours() * 60 + now.getMinutes();
        let current = null;
        let next = null;
        let wait = 10081;
        for (const lesson of lessons) {
            const day = Number(lesson.dataset.day) - 1;
            const start = day * 1440 + Number(lesson.dataset.start) * 60;
            const end = day * 1440 + Number(lesson.dataset.end) * 60;
            const active = time >= start && time < end;
            lesson.classList.toggle('current-lesson', active);
            if (active) current = lesson;
            let difference = start - time;
            if (difference <= 0) difference += 10080; // Minutes in one week.
            if (difference < wait) {
                wait = difference;
                next = lesson;
            }
        }
        status.textContent = 'V rozvrhu nemám žiadne hodiny.';
        if (next) status.textContent = 'Teraz nemám výučbu. Najbližšie mám ' + next.textContent.trim() + ' v ' + days[next.dataset.day - 1] + ' o ' + next.dataset.start + ':00.';
        if (current) status.textContent = 'Práve mám: ' + current.textContent.trim() + '.';
    }

    updateLesson();
    setInterval(updateLesson, 60000);

    updateSemester();
    setInterval(updateSemester, 60000);
}

function updateSemester() {
    const start = new Date(SEMESTER_START + 'T00:00:00');
    const end = new Date(SEMESTER_END + 'T23:59:59');
    const today = new Date();
    const totalTime = end - start;
    const elapsedTime = today - start;
    let percent = Math.round(elapsedTime / totalTime * 100);

    if (percent < 0) percent = 0;
    if (percent > 100) percent = 100;

    document.querySelector('#semester-percent').textContent = percent + ' %';
    document.querySelector('#progress-bar').style.width = percent + '%';
    document.querySelector('#semester-progress').setAttribute('aria-valuenow', percent);
    document.querySelector('#semester-dates').textContent = 'Semester: ' + start.toLocaleDateString('sk-SK') + ' – ' + end.toLocaleDateString('sk-SK');
}

async function setupWeather() {
    const weather = document.querySelector('#weather');
    if (!weather) return;
    try {
        const response = await fetch('https://api.open-meteo.com/v1/forecast?latitude=48.153&longitude=17.073&current=temperature_2m,wind_speed_10m,relative_humidity_2m');
        if (!response.ok) throw new Error('Weather request failed');
        const data = await response.json();
        const current = data.current;
        weather.textContent = 'Teplota: ' + current.temperature_2m + ' °C. Vietor: ' + current.wind_speed_10m + ' km/h. Vlhkosť: ' + current.relative_humidity_2m + ' %.';
    } catch (error) {
        weather.textContent = 'Počasie sa nepodarilo načítať. Skús obnoviť stránku.';
    }
}

